// Бесконечный режим (после победы): волны строятся по формуле, каждая пятая — с боссом.
// Летуны, лекари и броненосцы добавляются только на картах, где они уже встречались.
function endlessWave(n) {
  const k = n - WAVES.length, has = t => WAVES.some(w => w.some(g => g[0] === t));
  const groups = [['normal', 12 + 2 * k, 0.4], ['fast', 10 + 2 * k, 0.3], ['tank', 6 + k, 0.8]];
  if (has('fly')) groups.push(['fly', 8 + k, 0.5]);
  if (has('heal')) groups.splice(1, 0, ['heal', 3 + Math.floor(k / 2), 1.0]);
  if (has('armor')) groups.unshift(['armor', 6 + k, 0.8]);
  if (k % 5 === 0) groups.splice(Math.min(3, groups.length), 0, ['boss', 1 + Math.floor(k / 10), 3]);
  return groups;
}
