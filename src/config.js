// Бесконечный режим (после победы): волны строятся по формуле, каждая пятая — с боссом.
function endlessWave(n) {
  const k = n - WAVES.length;
  const groups = [['normal', 12 + 2 * k, 0.4], ['fast', 10 + 2 * k, 0.3], ['tank', 6 + k, 0.8]];
  if (k % 5 === 0) groups.splice(2, 0, ['boss', 1 + Math.floor(k / 10), 3]);
  return groups;
}
